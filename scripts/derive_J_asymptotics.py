#!/usr/bin/env python3
"""Derive the large-|ζ| expansions of the J functions used by the Z form (writes tsm_disp/_jasym.pxi).

With s = ζ Z(ζ) and u = 1/ζ², the J functions are quadratics in s:
    J_k = α_k + β_k s + γ_k s²,
and for Im ζ > 0, s ~ −Σ_n (2n−1)!!/2^n u^n. Substituting and expanding in u removes the
catastrophic cancellation of the closed forms at large |ζ| (e.g. J11 = −1 + s² = u + 7u²/4 + …).
"""
import sympy as sp

M = 48
u = sp.symbols("u")
z2 = 1 / u
s = -sum(sp.factorial2(2 * n - 1) / sp.Integer(2)**n * u**n for n in range(M + 3))
abg = {
    0: (-1, 0, 1),
    1: (2 * z2 + sp.Rational(1, 2), 2 * z2, sp.Rational(1, 2)),
    2: (1 - 2 * z2, -4 * z2, -(1 + 2 * z2)),
    3: (-sp.Rational(1, 2) - 5 * z2, -6 * z2, -(sp.Rational(3, 2) + z2)),
    4: (4 * z2**2 + 8 * z2 - 2, 8 * z2**2 + 12 * z2, 4 * z2**2 + 4 * z2 + 3),
}
lines = ["# generated by scripts/derive_J_asymptotics.py: J_k ~ Σ_m JASYM[k][m] u^m, u = 1/ζ²", 
         "DEF NJASYM = %d" % M, "cdef double JASYM[5][%d]" % M]
for k, (a, b_, g) in abg.items():
    ser = sp.series(sp.expand(a + b_ * s + g * s**2), u, 0, M + 1).removeO()
    poly = sp.Poly(sp.expand(ser), u)
    coeffs = [poly.coeff_monomial(u**m) for m in range(M + 1)]
    assert coeffs[0] == 0 or k in (), (k, coeffs[0])
    vals = [float(coeffs[m]) for m in range(1, M + 1)]   # JASYM[k][m-1] multiplies u^m
    lines.append("JASYM[%d][:] = [%s]" % (k, ", ".join(repr(v) for v in vals)))
    print("J%d:" % k, coeffs[:4])
sc = [float(sp.factorial2(2 * n - 1) / sp.Integer(2)**n) for n in range(M + 1)]
lines.append("cdef double SASYM[%d]" % (M + 1))
lines.append("SASYM[:] = [%s]" % ", ".join(repr(v) for v in sc))
open("tsm_disp/_jasym.pxi", "w").write("\n".join(lines) + "\n")
